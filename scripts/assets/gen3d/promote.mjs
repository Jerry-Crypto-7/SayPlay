#!/usr/bin/env node
/**
 * Zařadí modely z ops/gen3d, které prošly lidskou QA, do katalogu (P26C po dávce 281 slov).
 *
 *   node scripts/assets/gen3d/promote.mjs   karanténa → public/assets/worldstream/gen3d, catalog.json, catalog-index.json, disclosure.json
 *
 * Seznam schválených je `approved.json` (rozhodnutí QA, ne heuristika). Každý model
 * projde normalizací z CC0 cesty kvůli LOD1, kterou katalog vyžaduje; původní balík
 * z karantény se před tím odloží do `asset-quarantine/gen3d-source/`, aby opakovaný
 * běh normalizoval originál, ne vlastní výstup. Tag, který už nese jiný model, se přeskočí.
 */
import { copyFileSync, cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { normalizeModel, renderPreview, contactSheet } from '../cc0/normalize.mjs';
import { catalogIndex } from '../cc0/promote.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../../..');
const PUBLIC_DIR = 'public/assets/worldstream/gen3d';
const URL_BASE = '/assets/worldstream/gen3d';
const SOURCE_DIR = path.join(ROOT, 'asset-quarantine/gen3d-source');
const LICENSE = 'LicenseRef-Worldsmith-Generated';
const PROVENANCE = `${PUBLIC_DIR}/PROVENANCE.md`;

export const isGen3d = (asset) => asset.assetId.startsWith('gen3d-');

/** Hranice zaokrouhlené ven na 10 µm, jako u CC0: LOD1 z LOD0 vyčnívá o miliontiny metru. */
const outward = (bounds) => ({
  // Rezerva 1e-5: zjednodušené LOD1 harmoniky přesáhlo zdrojové meze o 3,4e-6.
  min: bounds.min.map((value, axis) => (axis === 1 ? value : Math.floor((value - 1e-5) * 1e5) / 1e5)),
  max: bounds.max.map((value) => Math.ceil((value + 1e-5) * 1e5) / 1e5),
});

const idOf = (noun) => `gen3d-${noun.replaceAll(' ', '-')}`;

function provenanceMarkdown(rows) {
  return [
    '# Generated models – provenance',
    '',
    'Models generated locally on an RTX 3090 by `ops/gen3d` (FLUX.2-klein-4B or Z-Image-Turbo image → BiRefNet background removal →',
    'TRELLIS.2-4B mesh via ComfyUI → Blender finishing → gltfpack), passed its quality gate, then a human QA pass over',
    '`evals/gen3d/batch-sheet.png` (26. 9. 2026, list in `scripts/assets/gen3d/approved.json`). LOD1 by `scripts/assets/cc0/normalize.mjs`.',
    '',
    `${LICENSE}: generated by the project's own pipeline, no third-party asset. Model licences: FLUX.2-klein-4B / Z-Image-Turbo Apache-2.0,`,
    'TRELLIS.2-4B MIT, BiRefNet MIT, DINOv3 image encoder under the DINOv3 License (see disclosure.json).',
    '',
    '| Model | Noun | Tags | Triangles LOD0/LOD1 |',
    '|---|---|---|---|',
    ...rows.map((row) => `| \`${row.assetId}\` | ${row.noun} | ${row.tags.join(', ')} | ${row.triangles.join(' / ')} |`),
    '',
  ].join('\n');
}

export async function promote({ root = ROOT } = {}) {
  const read = (file) => JSON.parse(readFileSync(path.join(root, file), 'utf8'));
  const { approved } = read('scripts/assets/gen3d/approved.json');
  const catalog = read('src/assets/catalog.json');
  const disclosure = read('disclosure.json');
  const publicDir = path.join(root, PUBLIC_DIR);
  rmSync(publicDir, { recursive: true, force: true });
  mkdirSync(publicDir, { recursive: true });

  const others = catalog.assets.filter((asset) => !isGen3d(asset));
  const taken = new Set(others.flatMap((asset) => [asset.assetId, ...asset.tags]));
  const entries = [];
  const rows = [];
  const skipped = [];

  for (const [noun, extra] of Object.entries(approved)) {
    const assetId = idOf(noun);
    const stash = path.join(SOURCE_DIR, assetId);
    if (!existsSync(stash)) cpSync(path.join(root, 'asset-quarantine', assetId), stash, { recursive: true });
    const tags = [noun, ...extra].filter((tag, i, all) => !taken.has(tag) && all.indexOf(tag) === i);
    if (!tags.includes(noun)) {
      skipped.push({ noun, reason: `"${noun}" is already a tag of another catalog model` });
      continue;
    }
    const original = JSON.parse(readFileSync(path.join(stash, 'candidate.json'), 'utf8')).assets[0];
    const record = await normalizeModel({
      input: path.join(stash, 'model.glb'), assetId, label: noun, tags,
      pack: { id: 'gen3d', pageUrl: 'ops/gen3d', author: original.provenance.author, license: LICENSE },
      licenseFile: path.join(stash, 'license-evidence.txt'), sourceFile: 'model.glb', style: false,
    });
    tags.forEach((tag) => taken.add(tag));
    const lods = [record.lod0, record.lod1].map((lod) => {
      const name = `${assetId}-lod${lod.level}.glb`;
      copyFileSync(lod.file, path.join(publicDir, name));
      return { level: lod.level, path: `${URL_BASE}/${name}`, hash: lod.hash, bytes: lod.bytes, triangles: lod.triangles, decodedGeometryBytes: lod.decodedGeometryBytes, decodedTextureBytes: lod.decodedTextureBytes, minScreenPixels: lod.level ? 0 : 160 };
    });
    writeFileSync(path.join(publicDir, `${assetId}.png`), await renderPreview(record.lod0.file));
    const { candidate } = record;
    entries.push({
      assetId, version: 1, hash: lods[0].hash, label: `${noun} (generated)`, tags, style: original.style,
      thumbnail: `${URL_BASE}/${assetId}.png`,
      provenance: { ...original.provenance, license: LICENSE, licenseEvidence: PROVENANCE },
      units: 'meters', up: '+Y', front: '+Z', pivot: [0, 0, 0], bounds: outward(candidate.bounds), stretchableAxes: [], lods,
      materials: candidate.materials, collision: candidate.collision, sockets: [], supportSurfaces: [], parts: candidate.parts,
    });
    rows.push({ assetId, noun, tags, triangles: lods.map((lod) => lod.triangles) });
    console.log(`${assetId}: ${lods[0].triangles}/${lods[1].triangles} triangles`);
  }

  const previews = rows.map((row) => ({ id: row.assetId, png: readFileSync(path.join(publicDir, `${row.assetId}.png`)) }));
  writeFileSync(path.join(publicDir, '_sheet.png'), await contactSheet(previews));
  writeFileSync(path.join(root, PROVENANCE), provenanceMarkdown(rows));

  catalog.assets = [...others, ...entries];
  writeFileSync(path.join(root, 'src/assets/catalog.json'), `${JSON.stringify(catalog, null, 2)}\n`);
  writeFileSync(path.join(root, 'src/assets/catalog-index.json'), `${JSON.stringify(catalogIndex(catalog), null, 2)}\n`);

  const records = readdirSync(publicDir).sort().map((file) => ({
    name: `${PUBLIC_DIR}/${file}`, kind: 'asset', firstParty: true,
    reason: file.endsWith('.glb')
      ? 'Model generated locally by ops/gen3d from a sentence noun, approved by human QA, LOD1 by scripts/assets/cc0/normalize.mjs.'
      : 'Preview render, contact sheet or provenance table of the generated models, written by scripts/assets/gen3d/promote.mjs.',
    source: 'ops/gen3d; scripts/assets/gen3d/promote.mjs',
    authorOrProvider: 'Worldsmith project – generated by ops/gen3d',
    license: LICENSE,
    requiredNotices: [`No third-party asset notice; generated by the project's own pipeline. See ${PROVENANCE}.`],
    attribution: 'Worldsmith generated models, 2026-09-26.',
    reviewNote: 'First-party output of local generation models whose licences are registered in disclosure.json (tool scope); no downloaded model or texture.',
    scope: 'prod',
  }));
  disclosure.entries = [...disclosure.entries.filter((entry) => !(entry.kind === 'asset' && entry.name.startsWith(`${PUBLIC_DIR}/`))), ...records];
  writeFileSync(path.join(root, 'disclosure.json'), `${JSON.stringify(disclosure, null, 2)}\n`);
  return { promoted: entries.length, skipped };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { promoted, skipped } = await promote();
  for (const { noun, reason } of skipped) console.warn(`skipped ${noun}: ${reason}`);
  console.log(`${promoted} generated models in the catalog, ${skipped.length} skipped`);
}
