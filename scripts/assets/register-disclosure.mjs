/** Register generated, first-party artifacts without changing library entries. */
import { readFile, readdir, writeFile } from 'node:fs/promises';
const root = new URL('../../', import.meta.url);
const file = new URL('disclosure.json', root);
const disclosure = JSON.parse(await readFile(file, 'utf8'));
const catalog = JSON.parse(await readFile(new URL('src/assets/catalog.json', root), 'utf8'));
// Model vyměněný pod stejným id (P57, `promote-batch.mjs --replace`) má záznam vygenerovaného modelu; původ adresáře by ho vrátil.
const replaced = new Set(catalog.assets.filter((asset) => asset.provenance.replacedAt)
  .flatMap((asset) => [...asset.lods.map((lod) => lod.path), asset.thumbnail]).map((url) => `public${url}`));

const ORIGINALS = {
  reason: 'Original Worldsmith model, generated preview or provenance document; authored locally from scripts/assets/originals.mjs without third-party geometry or textures.',
  source: 'scripts/assets/originals.mjs; scripts/assets/normalize.mjs',
  authorOrProvider: 'Worldsmith project — Codex-assisted original geometry',
  requiredNotices: ['No third-party asset notice; original project geometry. See public/assets/worldstream/PROVENANCE.md.'],
  attribution: 'Original Worldsmith starter models and generated previews, 2026-09-17.',
};
const GAME = {
  reason: 'Original Worldsmith game model, Blender preview or provenance document; assembled in Blender from primitive solids by scripts/assets/blender/game_models.py without third-party geometry, textures or generative 3D models.',
  source: 'scripts/assets/blender/game_models.py; scripts/assets/game-models.mjs',
  authorOrProvider: 'Worldsmith project — AI-assisted original geometry (Blender)',
  requiredNotices: ['No third-party asset notice; original project geometry. See public/assets/worldstream/game/PROVENANCE.md.'],
  attribution: 'Original Worldsmith game models and Blender previews, 2026-09-22.',
};
const ENV = {
  reason: 'Panorama sky/backdrop generated locally by ops/env/batch.py (FLUX.2 klein 4B, Apache-2.0) from a setting prompt; seam blended and encoded by ops/env/panorama.py.',
  source: 'ops/env/batch.py; ops/env/panorama.py',
  authorOrProvider: 'Worldsmith project – generated by ops/env',
  license: 'LicenseRef-Worldsmith-Generated',
  requiredNotices: ['No third-party asset notice; generated by the project\'s own pipeline. Prompts in src/play/arcade/look/env-catalog.json.'],
  attribution: 'Worldsmith generated panoramas (FLUX.2 [klein] 4B © Black Forest Labs, Apache-2.0), 2026-09-26.',
  reviewNote: 'First-party output of a local generation model whose licence is registered in disclosure.json (FLUX.2-klein-4B); no downloaded image or texture.',
};
const PLAY_ENV = {
  ...ENV,
  source: 'scripts/cloud/bake-panoramas.mjs; ops/env/batch.py; ops/env/panorama.py',
  requiredNotices: ['No third-party asset notice; generated by the project\'s own pipeline. Prompts in src/play/env/baked.json.'],
  attribution: 'Worldsmith pre-baked panoramas (FLUX.2 [klein] 4B © Black Forest Labs, Apache-2.0), 2026-09-27.',
};

async function register(dir, origin) {
  for (const entry of await readdir(new URL(`public/${dir}/`, root), { withFileTypes: true })) {
    const fullName = `public/${dir}/${entry.name}`;
    if (!entry.isFile() || replaced.has(fullName)) continue;
    const record = { name: fullName, kind: 'asset', firstParty: true, reason: origin.reason, source: origin.source,
      authorOrProvider: origin.authorOrProvider, license: origin.license ?? 'LicenseRef-Worldsmith-Original', requiredNotices: origin.requiredNotices,
      attribution: origin.attribution,
      reviewNote: origin.reviewNote ?? 'First-party, reproducible original geometry; no downloaded model or texture. No new license grant is asserted.', scope: 'prod' };
    const index = disclosure.entries.findIndex((e) => e.kind === 'asset' && e.name === fullName);
    if (index < 0) disclosure.entries.push(record); else disclosure.entries[index] = record;
  }
}

await register('assets/worldstream', ORIGINALS);
await register('assets/worldstream/game', GAME);
await register('assets/worldstream/env', ENV);
await register('play/env', PLAY_ENV);
await writeFile(file, `${JSON.stringify(disclosure, null, 2)}\n`);
