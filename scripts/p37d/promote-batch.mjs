#!/usr/bin/env node
/**
 * Povýší přijaté modely dávky `catalog-batch.v1` celým řetězem katalogu do PLAY (P37D T3).
 *
 *   node scripts/p37d/promote-batch.mjs --batch <catalog-batch.json>
 *
 * Dávku píše `scripts/p37d/judge-sheet.mjs --batch-out`. Každý záznam s `checked.verdict`
 * `pass` projde `normalizeModel` (LOD1, záznam katalogu), GLB a náhled jdou do
 * `public/assets/worldstream/gen3d-p37d/`, záznam do `src/assets/catalog.json`; pak
 * `catalog-index.json`, `disclosure.json`, `src/play/assets/entries/catalog.json`
 * (`scripts/assets/p32-manifest.mjs`) a `DISCLOSURE.md` (`license-gate --sync`).
 * Hrdinou se model stane, když jeho jméno zná třída v `p32-manifest.mjs` (frog = animal);
 * jinak do PLAY vede jen přes štítky indexu (předměty, překážky, soupeři).
 *
 * Nic nemaže. Vlastní adresář, protože starý `scripts/assets/gen3d/promote.mjs` maže
 * celé `gen3d/`. Model se stejným id z jiného adresáře se přeskočí, jméno, které už je
 * štítkem jiného modelu, se nezapíše, licence jiná než licence výroby se odmítne.
 * Opakované povýšení téhož id záznam nahradí, nezdvojí.
 *
 *   node scripts/p37d/promote-batch.mjs --batch <catalog-batch.json> --replace
 *
 * P57: vymění model, který už v katalogu je (i CC0 nebo starší gen3d), pod stejným id a na
 * stejných cestách. Id, štítky, kolize, sockety a pivot zůstanou, verze +1, hash, LOD a
 * `bounds` ze souboru. Odmítne rozměr mimo ±10 % v kterékoli ose a LOD1 těžší než starý.
 * Staré soubory jdou do `D:/caches/p57/replaced/<id>/v<verze>/` – návrat = zkopírovat zpět.
 */
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { getBounds } from '@gltf-transform/functions';

import { catalogIndex } from '../assets/cc0/promote.mjs';
import { HERO_MAX_TRIANGLES, normalizeModel, renderPreview } from '../assets/cc0/normalize.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain && !process.features.typescript) {
  const run = spawnSync(process.execPath, ['--experimental-strip-types', '--no-warnings', fileURLToPath(import.meta.url), ...process.argv.slice(2)], { stdio: 'inherit' });
  process.exit(run.status ?? 1);
}

export const PUBLIC_DIR = 'public/assets/worldstream/gen3d-p37d';
export const URL_BASE = '/assets/worldstream/gen3d-p37d';
export const LICENSE = 'LicenseRef-Worldsmith-Generated';
const PROVENANCE = `${PUBLIC_DIR}/PROVENANCE.md`;
const AUTHOR = 'Worldsmith project – generated by ops/gen3d';
const STYLE = 'generated low-poly vertex colour';
export const REPLACED_DIR = 'D:/caches/p57/replaced';
/** Kolize a zásahy zůstávají ze starého modelu, nový proto smí být v každé ose nejvýš o 10 % jinak velký. */
const MAX_SIZE_CHANGE = 0.1;
/** `outward` posune hranice ven nejvýš o 2e-5 m; víc už je jiný soubor. */
const BOUNDS_SLACK = 1e-4;

/** Hranice zaokrouhlené ven na 10 µm jako v `scripts/assets/gen3d/promote.mjs`: LOD1 z LOD0 vyčnívá o miliontiny metru. */
const outward = (bounds) => ({
  min: bounds.min.map((value, axis) => (axis === 1 ? value : Math.floor((value - 1e-5) * 1e5) / 1e5)),
  max: bounds.max.map((value) => Math.ceil((value + 1e-5) * 1e5) / 1e5),
});

export const isOurs = (asset) => asset.lods[0].path.startsWith(`${URL_BASE}/`);

const sourceOf = (entry) =>
  `Generated locally on an RTX 3090 by ${entry.source.pipeline}: ${entry.source.imageModel} (Apache-2.0) image, seed ${entry.source.seed} -> ` +
  `BiRefNet (MIT) background removal -> ${entry.source.shapeModel} (MIT) via ComfyUI (GPL-3.0, local tool, not distributed) -> ` +
  'Blender 5.1 finishing -> gltfpack 1.2.0 (MIT).';

const today = () => new Date().toISOString().slice(0, 10);
const extent = (bounds, axis) => bounds.max[axis] - bounds.min[axis];
/** Soubory modelu v repu: oba LOD a náhled. */
const filesOf = (asset) => [...asset.lods.map((lod) => lod.path), asset.thumbnail].map((url) => `public${url}`);
const io = () => new NodeIO().registerExtensions(ALL_EXTENSIONS);

const generatedRecord = (name, reason, attribution) => ({
  name, kind: 'asset', firstParty: true, reason,
  source: 'ops/gen3d; scripts/p37d/promote-batch.mjs',
  authorOrProvider: AUTHOR,
  license: LICENSE,
  requiredNotices: [`No third-party asset notice; generated by the project's own pipeline. See ${PROVENANCE}.`],
  attribution,
  reviewNote: 'First-party output of local generation models whose licences are registered in disclosure.json (tool scope); no downloaded model or texture.',
  scope: 'prod',
});

const TABLE_REASON = 'Preview render or provenance table of the generated models, written by scripts/p37d/promote-batch.mjs.';

function provenanceMarkdown(all) {
  const assets = all.filter(isOurs);
  const replaced = all.filter((asset) => asset.provenance.replacedAt);
  return [
    '# Generated models P37D – provenance',
    '',
    'Models generated locally on an RTX 3090 by `ops/gen3d` (FLUX.2-klein-4B or Z-Image-Turbo image → BiRefNet background removal →',
    'TRELLIS.2-4B mesh via ComfyUI → Blender finishing → gltfpack). Each passed the `ops/gen3d` quality gate, a blind judge over a',
    'four-view sheet (`scripts/p37d/judge-sheet.mjs`) and a look at the sheet; promoted by `scripts/p37d/promote-batch.mjs`,',
    'LOD1 by `scripts/assets/cc0/normalize.mjs`.',
    '',
    `${LICENSE}: generated by the project's own pipeline, no third-party asset. Model licences: FLUX.2-klein-4B / Z-Image-Turbo Apache-2.0,`,
    'TRELLIS.2-4B MIT, BiRefNet MIT, DINOv3 image encoder under the DINOv3 License (see disclosure.json).',
    '',
    '| Model | Tags | Triangles LOD0/LOD1 |',
    '|---|---|---|',
    ...assets.map((asset) => `| \`${asset.assetId}\` | ${asset.tags.join(', ')} | ${asset.lods.map((lod) => lod.triangles).join(' / ')} |`),
    '',
    ...(replaced.length === 0 ? [] : [
      '## Replaced in P57 under the same id',
      '',
      'Regenerated by the same pipeline and swapped in by `scripts/p37d/promote-batch.mjs --replace`: the catalog id, tags and collision',
      'stay, the geometry and its licence are new. The files they replaced are kept outside the repo, not distributed.',
      '',
      '| Model | Replaced | Was | Triangles LOD0/LOD1 |',
      '|---|---|---|---|',
      ...replaced.map((asset) => `| \`${asset.assetId}\` | replaced ${asset.provenance.replacedAt} | ${asset.provenance.replacedFrom} | ${asset.lods.map((lod) => lod.triangles).join(' / ')} |`),
      '',
    ]),
  ].join('\n');
}

/**
 * Zapíše přijaté záznamy dávky do katalogu pod `root`. `sync: false` vynechá
 * `p32-manifest` a `DISCLOSURE.md` – ty pracují nad repem, ne nad `root` (testy).
 */
export async function promoteBatch(batch, { root = ROOT, sync = true, drop = [] } = {}) {
  const read = (file) => JSON.parse(readFileSync(path.join(root, file), 'utf8'));
  const catalog = read('src/assets/catalog.json');
  const disclosure = read('disclosure.json');
  const publicDir = path.join(root, PUBLIC_DIR);
  mkdirSync(publicDir, { recursive: true });

  // Vyřazení (T5: druhý soud model nepoznal) bere jen vlastní modely gen3d-p37d, cizí id zůstane.
  const dropped = catalog.assets.filter((asset) => drop.includes(asset.assetId) && isOurs(asset)).map((asset) => asset.assetId);
  for (const id of dropped) for (const file of [`${id}-lod0.glb`, `${id}-lod1.glb`, `${id}.png`]) rmSync(path.join(publicDir, file), { force: true });
  const passed = batch.entries.filter((entry) => entry.checked.verdict === 'pass');
  const again = new Set(passed.map((entry) => entry.id).filter((id) => catalog.assets.some((asset) => asset.assetId === id && isOurs(asset))));
  const others = catalog.assets.filter((asset) => !again.has(asset.assetId) && !dropped.includes(asset.assetId));
  const taken = new Set(others.flatMap((asset) => [asset.assetId, ...asset.tags]));
  const skipped = batch.entries.filter((entry) => entry.checked.verdict !== 'pass').map((entry) => ({ id: entry.id, reason: `judge: ${entry.checked.judge}` }));
  const entries = [];

  for (const entry of passed) {
    const tags = entry.nouns.filter((noun, i, all) => !taken.has(noun) && all.indexOf(noun) === i);
    const reason =
      entry.licence !== LICENSE ? `licence ${entry.licence} is not the pipeline licence ${LICENSE}`
      : taken.has(entry.id) ? 'id already in the catalog outside gen3d-p37d'
      : !tags.includes(entry.nouns[0]) ? `"${entry.nouns[0]}" is already a tag of another catalog model`
      : null;
    if (reason) {
      skipped.push({ id: entry.id, reason });
      continue;
    }
    const work = mkdtempSync(path.join(os.tmpdir(), 'p37d-promote-'));
    try {
      const licenseFile = path.join(work, 'license-evidence.txt');
      writeFileSync(licenseFile, `${LICENSE}: ${sourceOf(entry)} Checked: ${entry.checked.judge}.\n`);
      let record;
      try {
        record = await normalizeModel({
          input: entry.glb, assetId: entry.id, label: entry.nouns[0], tags,
          pack: { id: 'gen3d', pageUrl: entry.source.pipeline, author: AUTHOR, license: LICENSE },
          licenseFile, sourceFile: path.basename(entry.glb), style: false,
        });
      } catch (error) {
        // Páv z dávky 1 (4. 10.): tenká pera nejde zjednodušit na LOD1 při stejné velikosti – model ven, dávka dál.
        skipped.push({ id: entry.id, reason: `normalize: ${error.message}` });
        continue;
      }
      const lods = [record.lod0, record.lod1].map((lod) => {
        const name = `${entry.id}-lod${lod.level}.glb`;
        copyFileSync(lod.file, path.join(publicDir, name));
        return { level: lod.level, path: `${URL_BASE}/${name}`, hash: lod.hash, bytes: lod.bytes, triangles: lod.triangles, decodedGeometryBytes: lod.decodedGeometryBytes, decodedTextureBytes: lod.decodedTextureBytes, minScreenPixels: lod.level ? 0 : 160 };
      });
      writeFileSync(path.join(publicDir, `${entry.id}.png`), await renderPreview(record.lod0.file));
      const { candidate } = record;
      entries.push({
        assetId: entry.id, version: 1, hash: lods[0].hash, label: `${entry.nouns[0]} (generated)`, tags, style: STYLE,
        thumbnail: `${URL_BASE}/${entry.id}.png`,
        provenance: { ...candidate.provenance, source: sourceOf(entry), author: AUTHOR, license: LICENSE, licenseEvidence: PROVENANCE },
        units: 'meters', up: '+Y', front: '+Z', pivot: [0, 0, 0], bounds: outward(candidate.bounds), stretchableAxes: [], lods,
        materials: candidate.materials, collision: candidate.collision, sockets: [], supportSurfaces: [], parts: candidate.parts,
      });
      [entry.id, ...tags].forEach((tag) => taken.add(tag));
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  }

  catalog.assets = [...others, ...entries];
  writeFileSync(path.join(root, PROVENANCE), provenanceMarkdown(catalog.assets));
  writeFileSync(path.join(root, 'src/assets/catalog.json'), `${JSON.stringify(catalog, null, 2)}\n`);
  writeFileSync(path.join(root, 'src/assets/catalog-index.json'), `${JSON.stringify(catalogIndex(catalog), null, 2)}\n`);

  const records = readdirSync(publicDir).sort().map((file) => generatedRecord(
    `${PUBLIC_DIR}/${file}`,
    file.endsWith('.glb')
      ? 'Model generated locally by ops/gen3d from a noun jurors write, passed its quality gate and a blind four-view judge, LOD1 by scripts/assets/cc0/normalize.mjs.'
      : TABLE_REASON,
    'Worldsmith generated models P37D, 2026-10.',
  ));
  disclosure.entries = [...disclosure.entries.filter((entry) => !(entry.kind === 'asset' && entry.name.startsWith(`${PUBLIC_DIR}/`))), ...records];
  writeFileSync(path.join(root, 'disclosure.json'), `${JSON.stringify(disclosure, null, 2)}\n`);

  if (sync) syncCatalog(root);
  return { promoted: entries.map((entry) => entry.assetId), skipped, dropped };
}

function syncCatalog(root) {
  for (const args of [['scripts/assets/p32-manifest.mjs'], ['scripts/license-gate.mjs', '--sync']]) {
    const run = spawnSync(process.execPath, args, { cwd: root, stdio: 'inherit' });
    if (run.status !== 0) throw new Error(`${args.join(' ')} failed with exit ${run.status}`);
  }
}

/**
 * Vymění modely, které už v katalogu jsou, pod stejným id (P57). Nic nezapíše, když
 * žádný neprojde; staré soubory zkopíruje do `replacedDir/<id>/v<verze>/` dřív, než je přepíše.
 * `profile: 'hero'` (P57 T8) pustí LOD0 až k `HERO_MAX_TRIANGLES` a LOD1 zjednoduší na starý LOD1.
 */
export async function replaceModels(batch, { root = ROOT, sync = true, replacedDir = REPLACED_DIR, profile = 'default' } = {}) {
  const read = (file) => JSON.parse(readFileSync(path.join(root, file), 'utf8'));
  const catalog = read('src/assets/catalog.json');
  const disclosure = read('disclosure.json');
  const skipped = batch.entries.filter((entry) => entry.checked.verdict !== 'pass').map((entry) => ({ id: entry.id, reason: `judge: ${entry.checked.judge}` }));
  const replaced = [];

  for (const entry of batch.entries.filter((entry) => entry.checked.verdict === 'pass')) {
    const index = catalog.assets.findIndex((asset) => asset.assetId === entry.id);
    const old = catalog.assets[index];
    const refused = !old ? 'not in the catalog, nothing to replace'
      : entry.licence !== LICENSE ? `licence ${entry.licence} is not the pipeline licence ${LICENSE}`
      : null;
    if (refused) {
      skipped.push({ id: entry.id, reason: refused });
      continue;
    }
    const work = mkdtempSync(path.join(os.tmpdir(), 'p57-replace-'));
    const oldLod1 = old.lods.find((lod) => lod.level === 1);
    try {
      const licenseFile = path.join(work, 'license-evidence.txt');
      writeFileSync(licenseFile, `${LICENSE}: ${sourceOf(entry)} Checked: ${entry.checked.judge}.\n`);
      let record;
      try {
        record = await normalizeModel({
          input: entry.glb, assetId: entry.id, label: old.tags[0], tags: old.tags,
          pack: { id: 'gen3d', pageUrl: entry.source.pipeline, author: AUTHOR, license: LICENSE },
          licenseFile, sourceFile: path.basename(entry.glb), style: false,
          ...(profile === 'hero' ? { maxTriangles: HERO_MAX_TRIANGLES, lod1Max: oldLod1.triangles } : {}),
        });
      } catch (error) {
        skipped.push({ id: entry.id, reason: `normalize: ${error.message}` });
        continue;
      }
      const bounds = outward(record.candidate.bounds);
      const axis = [0, 1, 2].find((axis) => Math.abs(extent(bounds, axis) / extent(old.bounds, axis) - 1) > MAX_SIZE_CHANGE);
      if (axis !== undefined) {
        const change = Math.round((extent(bounds, axis) / extent(old.bounds, axis) - 1) * 100);
        skipped.push({ id: entry.id, reason: `bounds: ${'xyz'[axis]} ${extent(old.bounds, axis).toFixed(3)} -> ${extent(bounds, axis).toFixed(3)} m (${change > 0 ? '+' : ''}${change} %), over ±${MAX_SIZE_CHANGE * 100} %` });
        continue;
      }
      if (record.lod1.triangles > oldLod1.triangles) {
        skipped.push({ id: entry.id, reason: `lod1: ${record.lod1.triangles} triangles, the replaced model had ${oldLod1.triangles}` });
        continue;
      }

      const aside = path.join(replacedDir, entry.id, `v${old.version}`);
      mkdirSync(aside, { recursive: true });
      for (const name of filesOf(old)) copyFileSync(path.join(root, name), path.join(aside, path.basename(name)));
      const lods = old.lods.map((lod) => {
        const fresh = lod.level === 0 ? record.lod0 : record.lod1;
        copyFileSync(fresh.file, path.join(root, `public${lod.path}`));
        return { ...lod, hash: fresh.hash, bytes: fresh.bytes, triangles: fresh.triangles, decodedGeometryBytes: fresh.decodedGeometryBytes, decodedTextureBytes: fresh.decodedTextureBytes };
      });
      writeFileSync(path.join(root, `public${old.thumbnail}`), await renderPreview(record.lod0.file));
      const date = today();
      catalog.assets[index] = {
        ...old, version: old.version + 1, hash: lods[0].hash,
        // „Grass (CC0, Quaternius)“ by po výměně lhalo o autorovi.
        label: `${old.label.replace(/\s*\([^)]*\)$/, '')} (generated)`, style: STYLE,
        provenance: {
          source: `${sourceOf(entry)} Swapped in under the same id by scripts/p37d/promote-batch.mjs --replace (P57).`,
          author: AUTHOR, license: LICENSE, licenseEvidence: PROVENANCE, importedAt: date, sourceHash: record.candidate.provenance.sourceHash,
          replacedAt: date, replacedFrom: old.provenance.replacedFrom ?? old.provenance.source,
        },
        bounds, lods, materials: record.candidate.materials, parts: record.candidate.parts,
      };
      for (const name of filesOf(old)) {
        const fresh = generatedRecord(name, name.endsWith('.glb')
          ? `Model generated locally by ops/gen3d and swapped in under the id of the model it replaced (P57), passed a blind 1-10 judge; LOD1 by scripts/assets/cc0/normalize.mjs.`
          : 'Preview render of a model generated locally by ops/gen3d under the id of the model it replaced (P57).', 'Worldsmith generated models P57, 2026-10.');
        const at = disclosure.entries.findIndex((other) => other.kind === 'asset' && other.name === name);
        if (at < 0) disclosure.entries.push(fresh); else disclosure.entries[at] = fresh;
      }
      replaced.push(entry.id);
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  }
  if (replaced.length === 0) return { replaced, skipped };

  mkdirSync(path.join(root, PUBLIC_DIR), { recursive: true });
  writeFileSync(path.join(root, PROVENANCE), provenanceMarkdown(catalog.assets));
  if (!disclosure.entries.some((entry) => entry.kind === 'asset' && entry.name === PROVENANCE)) disclosure.entries.push(generatedRecord(PROVENANCE, TABLE_REASON, 'Worldsmith generated models P37D, 2026-10.'));
  writeFileSync(path.join(root, 'src/assets/catalog.json'), `${JSON.stringify(catalog, null, 2)}\n`);
  writeFileSync(path.join(root, 'src/assets/catalog-index.json'), `${JSON.stringify(catalogIndex(catalog), null, 2)}\n`);
  writeFileSync(path.join(root, 'disclosure.json'), `${JSON.stringify(disclosure, null, 2)}\n`);
  if (sync) syncCatalog(root);
  return { replaced, skipped };
}

/** Problémy vyměněných modelů (P57): soubory, `bounds` proti LOD0, licence v katalogu i v disclosure. Prázdné pole = v pořádku. */
export async function checkReplaced({ catalog, disclosure, root = ROOT }) {
  const records = new Map(disclosure.entries.filter((entry) => entry.kind === 'asset').map((entry) => [entry.name, entry]));
  const problems = [];
  for (const asset of catalog.assets.filter((asset) => asset.provenance.replacedAt)) {
    if (asset.version < 2) problems.push(`${asset.assetId}: replaced but still version ${asset.version}`);
    if (asset.provenance.license !== LICENSE || !asset.provenance.replacedFrom) problems.push(`${asset.assetId}: provenance says ${asset.provenance.license}, replaced from ${asset.provenance.replacedFrom}`);
    for (const name of filesOf(asset)) {
      if (!existsSync(path.join(root, name))) problems.push(`${asset.assetId}: ${name} is missing`);
      const record = records.get(name);
      if (record?.license !== LICENSE || record.firstParty !== true) problems.push(`${asset.assetId}: ${name} is disclosed as ${record?.license ?? 'nothing'}, not first-party ${LICENSE}`);
    }
    const lod0 = path.join(root, `public${asset.lods[0].path}`);
    if (!existsSync(lod0)) continue;
    const { min, max } = getBounds((await io().read(lod0)).getRoot().listScenes()[0]);
    const axis = [0, 1, 2].find((axis) => Math.abs(min[axis] - asset.bounds.min[axis]) > BOUNDS_SLACK || Math.abs(max[axis] - asset.bounds.max[axis]) > BOUNDS_SLACK);
    if (axis !== undefined) problems.push(`${asset.assetId}: bounds ${'xyz'[axis]} [${asset.bounds.min[axis]}, ${asset.bounds.max[axis]}] in the catalog, [${min[axis]}, ${max[axis]}] in ${asset.lods[0].path}`);
  }
  return problems;
}

if (isMain) {
  const args = process.argv.slice(2);
  const file = args.includes('--batch') ? path.resolve(args[args.indexOf('--batch') + 1]) : null;
  const drop = args.includes('--drop') ? args[args.indexOf('--drop') + 1].split(',') : [];
  const replace = args.includes('--replace');
  if ((!file && drop.length === 0) || (replace && (!file || drop.length > 0))) {
    console.error('usage: node scripts/p37d/promote-batch.mjs --batch <catalog-batch.json> [--replace] | --drop <id,id>');
    process.exit(2);
  }
  let batch = { schema: 'catalog-batch.v1', entries: [] };
  if (file) {
    const { readBatch } = await import('../../src/play/assets/batch.ts');
    const read = readBatch(file);
    if (!read.ok) {
      console.error(`invalid batch ${file}:\n${read.issues.join('\n')}`);
      process.exit(1);
    }
    batch = read.batch;
  }
  if (replace) {
    const { replaced, skipped } = await replaceModels(batch);
    for (const { id, reason } of skipped) console.warn(`skipped ${id}: ${reason}`);
    console.log(`${replaced.length} models replaced under the same id (${replaced.join(', ')}), ${skipped.length} skipped, old files in ${REPLACED_DIR}`);
    process.exit(0);
  }
  const { promoted, skipped, dropped } = await promoteBatch(batch, { drop });
  for (const { id, reason } of skipped) console.warn(`skipped ${id}: ${reason}`);
  console.log(`${promoted.length} models promoted into PLAY (${promoted.join(', ')}), ${skipped.length} skipped, dropped: ${dropped.join(', ') || 'none'}`);
}
