#!/usr/bin/env node
/**
 * Povýší přijaté modely dávky `catalog-batch.v1` celým řetězem katalogu do PLAY (P37D T3).
 *
 *   node scripts/p37d/promote-batch.mjs --batch <catalog-batch.json>
 *
 * Dávku píše `scripts/p37d/judge-sheet.mjs --batch-out`. Každý záznam s `checked.verdict`
 * `pass` projde `normalizeModel` (LOD1, záznam katalogu), GLB a náhled jdou do
 * `public/assets/worldstream/gen3d-p37d/`, záznam do `src/assets/catalog.json`; pak
 * `catalog-index.json`, `disclosure.json`, `src/play/assets/entries/catalog.json`
 * (`scripts/assets/p32-manifest.mjs`) a `DISCLOSURE.md` (`license-gate --sync`).
 * Hrdinou se model stane, když jeho jméno zná třída v `p32-manifest.mjs` (frog = animal);
 * jinak do PLAY vede jen přes štítky indexu (předměty, překážky, soupeři).
 *
 * Nic nemaže. Vlastní adresář, protože starý `scripts/assets/gen3d/promote.mjs` maže
 * celé `gen3d/`. Model se stejným id z jiného adresáře se přeskočí, jméno, které už je
 * štítkem jiného modelu, se nezapíše, licence jiná než licence výroby se odmítne.
 * Opakované povýšení téhož id záznam nahradí, nezdvojí.
 *
 *   node scripts/p37d/promote-batch.mjs --batch <catalog-batch.json> --replace
 *
 * P57: vymění model, který už v katalogu je (i CC0 nebo starší gen3d), pod stejným id a na
 * stejných cestách. Id, štítky, kolize, sockety a pivot zůstanou, verze +1, hash, LOD a
 * `bounds` ze souboru. Odmítne rozměr mimo ±10 % v kterékoli ose a LOD1 těžší než starý.
 * Staré soubory jdou do `D:/caches/p57/replaced/<id>/v<verze>/` – návrat = zkopírovat zpět.
 * `replaceModels(..., { origin: 'cc0' })` (P57 T8r, `scripts/p57/cc0-veg.mjs`) vymění za soubor
 * z CC0 balíku: licence, autor a text licence z `scripts/assets/cc0/sources.json` a cache balíků.
 */
